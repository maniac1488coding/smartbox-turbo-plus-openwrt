#!/bin/sh /etc/rc.common
# /etc/init.d/bootcount_early
#
# Ранний сброс счётчика неудачных загрузок OEM-загрузчика Sercomm.
#
# ПРОБЛЕМА
# Загрузчик Sercomm на Beeline SmartBox TURBO+ ведёт в разделе "Boot Flag"
# (mtd3, смещение 0x20000) счётчик попыток загрузки. На каждом старте он
# увеличивает его. Если ОС успешно загрузилась, она должна вернуть счётчик
# в 0xff. Если три загрузки подряд не дошли до этого момента, загрузчик
# переключает Boot Flag с Sercomm0 на Sercomm1 и грузит СТОКОВУЮ прошивку
# из второго слота (mtd5 + mtd7).
#
# Штатный OpenWrt-скрипт /etc/init.d/bootcount делает сброс на "S99",
# то есть в самом конце загрузки. Любая просадка питания, зависание или
# быстрый ребут до этого момента оставляет счётчик заряженным; три таких
# события подряд — и роутер уходит в сток.
#
# РЕШЕНИЕ
# Тот же сброс, но на самом раннем шаге rcS (S00) плюс на штатном
# выключении. Окно уязвимости сокращается с десятков секунд до ~1 секунды.
#
# Штатный /etc/init.d/bootcount НЕ трогаем — он остаётся как дублирующая
# страховка.

START=00
STOP=99

# Второй стираемый блок раздела "Boot Flag" — там загрузчик держит счётчик.
BC_OFF=$((0x20000))
HIST=/root/bootcount-history.log

reset_counter() {
	printf '\377\377\377\377\377\377\377\377' | \
		dd of=/dev/mtdblock3 bs=1 seek=$BC_OFF count=8 2>/dev/null
}

boot() {
	# Сначала зафиксировать в истории то, что успел записать загрузчик.
	mkdir -p /root
	{
		printf '=== %s uptime=%ss ===\n' \
			"$(date '+%F %T')" "$(cut -d. -f1 /proc/uptime)"
		hexdump -Cn 16 -s $BC_OFF /dev/mtd3 2>/dev/null
	} >> $HIST

	# Затем обнулить счётчик как можно раньше.
	reset_counter
}

stop() {
	reset_counter
}
